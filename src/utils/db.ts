//Migration Utils
export const checkTableExists = async (
    knex: any,
    tableName: string,
): Promise<boolean> => {
    try {
        const result = await knex.raw(
            'SELECT 1 FROM RDB$RELATIONS WHERE TRIM(RDB$RELATION_NAME) = ?',
            [tableName.toUpperCase()],
        );
        const rows = result?.response || result;
        return rows && rows.length > 0;
    } catch (e) {
        return false;
    }
};

export const checkColumnExists = async (
    knex: any,
    tableName: string,
    columnName: string,
): Promise<boolean> => {
    try {
        const result = await knex.raw(
            'SELECT 1 FROM RDB$RELATION_FIELDS WHERE TRIM(RDB$RELATION_NAME) = ? AND TRIM(RDB$FIELD_NAME) = ?',
            [tableName.toUpperCase(), columnName.toUpperCase()],
        );
        const rows = result?.response || result;
        return rows && rows.length > 0;
    } catch (e) {
        return false;
    }
};

